def analyze_writing_style(blogger_name):
    """分析单个博主的写作风格"""

    articles = SAMPLE_ARTICLES.get(blogger_name, [])

    if not articles:
        return None

    analysis = {
        "blogger": blogger_name,
        "sample_count": len(articles),
        "avg_length": sum(a['length'] for a in articles) / len(articles),
        "common_structures": [],
        "tone_characteristics": [],
        "opening_patterns": [],
        "key_features": []
    }

    # 提取共同特征
    for article in articles:
        analysis["opening_patterns"].append(article["opening"][:50] + "...")
        analysis["key_features"].extend(article["features"])

    # 去重
    analysis["key_features"] = list(set(analysis["key_features"]))

    return analysis


